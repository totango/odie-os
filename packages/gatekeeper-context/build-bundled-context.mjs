import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = new URL(".", import.meta.url);
const sourceDir = path.join(root.pathname, "bundled-context");
const outFile = path.join(root.pathname, "src/generated/bundled-context.ts");

function json(value) {
  return JSON.stringify(value, null, 2);
}

function contentType(filePath) {
  if (filePath.endsWith(".json")) return "application/json";
  if (filePath.endsWith(".yaml") || filePath.endsWith(".yml")) return "application/yaml";
  if (filePath.endsWith(".txt")) return "text/plain";
  return "text/markdown";
}

async function walk(dir, base = "") {
  let entries = await readdir(dir, { withFileTypes: true });
  let result = [];
  for (let entry of entries) {
    let rel = base ? `${base}/${entry.name}` : entry.name;
    let full = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...await walk(full, rel));
    else if (entry.isFile() && entry.name !== "collection.json") result.push(rel);
  }
  return result.toSorted((a, b) => a.localeCompare(b));
}

async function build() {
  let dirs = (await readdir(sourceDir, { withFileTypes: true }))
      .filter(entry => entry.isDirectory())
      .map(entry => entry.name)
      .toSorted((a, b) => a.localeCompare(b));
  let collections = [];

  for (let dir of dirs) {
    let collectionDir = path.join(sourceDir, dir);
    let metadata = JSON.parse(await readFile(path.join(collectionDir, "collection.json"), "utf8"));
    if (metadata.id !== dir) throw new Error(`${dir}: collection id must match directory name`);
    let files = await walk(collectionDir);
    let docs = [];
    for (let file of files) {
      let body = await readFile(path.join(collectionDir, file), "utf8");
      let description = body
          .split(/\r?\n/)
          .find(line => line.trim() && !line.startsWith("---") && !line.startsWith("name:") && !line.startsWith("description:"))
          ?.replace(/^#+\s*/, "")
          .trim() ?? metadata.description;
      docs.push({
        path: file,
        name: path.basename(file),
        description,
        contentType: contentType(file),
        body,
        lastUpdated: new Date(metadata.updatedAt),
      });
    }
    let fingerprint = createHash("sha256")
        .update(json({ metadata, documents: docs.map(doc => ({ path: doc.path, body: doc.body })) }))
        .digest("hex");
    collections.push({
      id: metadata.id,
      icon: metadata.icon,
      title: metadata.title,
      description: metadata.description,
      visibility: "public",
      created: new Date(metadata.updatedAt),
      lastUpdated: new Date(metadata.updatedAt),
      documentCount: docs.length,
      content: { source: "bundled", fingerprint },
      documents: docs,
    });
  }

  let manifestFingerprint = createHash("sha256")
      .update(json(collections.map(collection => ({ id: collection.id, fingerprint: collection.content.fingerprint }))))
      .digest("hex");
  let source = `// Generated by build-bundled-context.mjs; do not edit by hand.\n` +
    `import type { BundledContextCollection } from "../bundled-context.js";\n\n` +
    `export const BUNDLED_CONTEXT_MANIFEST = ${json({ fingerprint: manifestFingerprint })} as const;\n\n` +
    `export const BUNDLED_CONTEXT_COLLECTIONS = ${json(collections)} as unknown as BundledContextCollection[];\n`;
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, source);
}

await build();
